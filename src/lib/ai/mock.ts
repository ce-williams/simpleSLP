import type { AIProvider, TreatmentPlanInput, ActivityInput, ProgressNoteInput, PatientSummaryInput, PayerProgressReportInput } from './provider';
import type { TreatmentPlanOutput, ActivityOutput, ProgressNoteOutput, PatientSummaryOutput, PayerProgressReportOutput } from './schemas';

export class MockProvider implements AIProvider {
  readonly name = 'mock_provider';

  async generateTreatmentPlan(input: TreatmentPlanInput): Promise<TreatmentPlanOutput> {
    const caseData = input.caseData as Record<string, string>;
    const precautions = JSON.parse((caseData.precautions as string) || '[]') as string[];
    const diagnoses = JSON.parse((caseData.diagnoses as string) || '[]') as string[];
    const caregiverInfo = JSON.parse((caseData.caregiver_participation as string) || '{}');

    const resourceIds = input.resources.map(r => (r as Record<string, string>).id).filter(Boolean);

    const suggestedInterventions = input.goals.map((g: Record<string, unknown>) => {
      const goalDesc = g.description as string;
      return {
        name: `Structured practice for: ${(goalDesc || '').slice(0, 40)}`,
        description: `A graded approach targeting ${goalDesc}, using available materials and caregiver involvement where appropriate.`,
        rationale: `Aligns with current goal status and available resources. Based on review of similar documented approaches.`,
        resource_ids: resourceIds.slice(0, 2),
        knowledge_type: 'ai_generated' as const,
      };
    });

    const precautionConflicts: TreatmentPlanOutput['precaution_conflicts'] = [];
    for (const p of precautions) {
      const lower = p.toLowerCase();
      if (lower.includes('aspiration') || lower.includes('swallowing')) {
        precautionConflicts.push({
          precaution: p,
          conflicting_suggestion: 'Any oral feeding trials without medical clearance',
          resolution: 'Removed oral feeding suggestions. Refer to medical team for swallowing evaluation before proceeding with oral trials.',
        });
      }
    }

    const missingInfo: string[] = [];
    if (!caseData.equipment_available || JSON.parse(caseData.equipment_available).length === 0) {
      missingInfo.push('Equipment/materials inventory not documented');
    }
    if (input.outcomes.length === 0) {
      missingInfo.push('No outcome data recorded yet — baseline measurements needed');
    }
    if (!caregiverInfo.stated_priorities || caregiverInfo.stated_priorities.length === 0) {
      missingInfo.push('Caregiver priorities not documented');
    }

    return {
      clinical_summary: `${diagnoses.join(', ')} case in ${caseData.setting?.replace(/_/g, ' ')} setting, age band ${caseData.age_band}. ${input.goals.length} active goal(s) with ${input.outcomes.length} outcome measurement(s) recorded across ${input.sessions.length} session(s). ${input.barriers.length} barrier(s) documented.`,
      missing_information: missingInfo,
      clarifying_questions: missingInfo.length > 0
        ? ['Are there additional medical restrictions not yet documented?', 'What is the caregiver\'s availability for home practice?']
        : [],
      proposed_goals: input.goals.map((g: Record<string, unknown>) => ({
        description: `Continue: ${g.description}`,
        rationale: 'Goal remains active with documented progress trajectory.',
        measurement_method: `Track ${(g as Record<string, string>).target_unit || 'progress'} per session using direct observation.`,
        knowledge_type: 'ai_generated' as const,
      })),
      suggested_interventions: suggestedInterventions,
      safety_considerations: [
        ...precautions.map(p => `Documented precaution: ${p}`),
        'Monitor for signs of distress during all feeding trials.',
        'Stop activity if child shows signs of respiratory difficulty, gagging, or emotional dysregulation beyond typical range.',
      ],
      alternatives: [{
        description: 'Indirect therapy approach focusing on environmental modifications',
        rationale: 'If direct intervention produces elevated distress, environmental modifications may reduce barriers before re-attempting direct techniques.',
      }],
      citations: resourceIds.slice(0, 3).map(id => ({
        resource_id: id,
        context: 'Referenced as background for intervention approach. Verify resource before clinical application.',
      })),
      limitations: [
        'This plan was generated by a template-based mock provider and should not be treated as clinical evidence.',
        'All suggestions require clinician review and modification based on clinical judgment.',
        `Based on ${input.similarCases.length} similar case(s) found in the database — similarity does not imply the same outcomes will occur.`,
      ],
      precaution_conflicts: precautionConflicts,
      requires_clinician_review: true,
    };
  }

  async generateActivity(input: ActivityInput): Promise<ActivityOutput> {
    const theme = input.patientInterests.length > 0
      ? input.patientInterests[0]
      : 'adventure';

    return {
      name: `${theme.charAt(0).toUpperCase() + theme.slice(1)} Exploration Station`,
      premise: `A ${theme}-themed activity where the child explores new textures and movements through play, working toward the target goal in a low-pressure format.`,
      target_goal: input.targetGoal,
      why_it_fits: `Designed for ${input.developmentalLevel} developmental level in a ${input.setting.replace(/_/g, ' ')} setting, using available materials and fitting within ${input.timeAvailable} minutes.`,
      materials: [
        { item: 'Small containers or cups', alternatives: ['bowls', 'muffin tins', 'ice cube trays'] },
        { item: 'Sensory-safe food items matching therapy targets', alternatives: ['play dough', 'textured fabric squares'] },
        ...(input.availableTools.length > 0
          ? [{ item: input.availableTools[0], alternatives: input.availableTools.slice(1, 3) }]
          : []),
      ],
      prep_steps: [
        'Set up workspace with washable surface covering.',
        'Prepare materials in small, manageable portions.',
        `Allow ${Math.min(5, input.timeAvailable)} minutes for child to observe materials before engaging.`,
      ],
      instructions: [
        'Present materials in a non-demanding way — "Look what we have today."',
        'Model interaction with materials using exaggerated, positive affect.',
        'Follow the child\'s lead — if they show interest in a specific item, expand on that.',
        'Introduce the target skill within the play context when the child is engaged.',
        'Offer verbal praise for any interaction with materials.',
        'Transition to cleanup using a visual or verbal countdown.',
      ],
      grading: {
        up: [
          'Increase variety of materials presented.',
          'Add a social component (peer or caregiver participation).',
          'Reduce modeling support and increase independent exploration time.',
        ],
        down: [
          'Reduce number of materials to 1-2.',
          'Increase modeling and hand-over-hand support.',
          'Shorten activity duration and add more frequent breaks.',
        ],
      },
      measurement: `Record duration of engagement, number of interactions with target materials, and assistance level. Compare to baseline for ${input.targetGoal}.`,
      safety_notes: [
        'Ensure all materials are age-appropriate and non-toxic.',
        'Monitor for signs of oral aversion or distress.',
        ...(input.accessibilityNeeds.length > 0
          ? [`Accessibility: ${input.accessibilityNeeds.join(', ')}`]
          : []),
      ],
      stop_criteria: [
        'Child shows persistent distress beyond 2 minutes of coping strategies.',
        'Any signs of choking, gagging, or respiratory difficulty.',
        'Child requests to stop (verbal or gestural).',
      ],
      provenance: 'Generated by MockProvider using template-based activity design. This is an AI-generated draft requiring clinician review and modification.',
      knowledge_type: 'ai_generated',
    };
  }

  async generateProgressNote(input: ProgressNoteInput): Promise<ProgressNoteOutput> {
    const session = input.session as Record<string, unknown>;
    const caseData = input.caseData as Record<string, string>;

    const sections: ProgressNoteOutput['sections'] = [];

    sections.push({
      heading: 'Session Information',
      content: `${session.duration_minutes}-minute session on ${session.session_date} in ${(session.setting as string || '').replace(/_/g, ' ')} setting. ${session.caregiver_present ? 'Caregiver was present.' : 'Caregiver was not present.'}`,
      source_records: [`session:${session.id}`],
    });

    if (input.interventions.length > 0) {
      const intDescriptions = input.interventions.map((int: Record<string, unknown>) =>
        `${int.name}: ${int.description}`
      ).join('\n');
      sections.push({
        heading: 'Interventions',
        content: intDescriptions,
        source_records: input.interventions.map((int: Record<string, unknown>) => `intervention:${int.id}`),
      });
    }

    if (input.outcomes.length > 0) {
      const outDescriptions = input.outcomes.map((out: Record<string, unknown>) =>
        `${out.metric}: ${out.value} ${out.unit}${out.assistance_level ? ` (${out.assistance_level})` : ''}`
      ).join('\n');
      sections.push({
        heading: 'Outcomes',
        content: outDescriptions,
        source_records: input.outcomes.map((out: Record<string, unknown>) => `outcome:${out.id}`),
      });
    }

    if (input.barriers.length > 0) {
      const barrierDescriptions = input.barriers.map((b: Record<string, unknown>) =>
        `[${b.category}] ${b.description}`
      ).join('\n');
      sections.push({
        heading: 'Barriers',
        content: barrierDescriptions,
        source_records: input.barriers.map((b: Record<string, unknown>) => `barrier:${b.id}`),
      });
    }

    if (session.notes) {
      sections.push({
        heading: 'Clinical Notes',
        content: session.notes as string,
        source_records: [`session:${session.id}`],
      });
    }

    sections.push({
      heading: 'Plan',
      content: `Continue current goals. ${input.barriers.length > 0 ? 'Address documented barriers in next session planning.' : ''} ${session.caregiver_present ? 'Reinforce caregiver home program.' : 'Coordinate with caregiver regarding home practice.'}`,
      source_records: [],
    });

    return {
      sections,
      unsupported_content: [],
      knowledge_type: 'ai_generated',
    };
  }

  async generatePayerProgressReport(input: PayerProgressReportInput): Promise<PayerProgressReportOutput> {
    const caseData = input.caseData as Record<string, string>;
    const diagnoses = JSON.parse(caseData.diagnoses || '[]') as string[];
    const caregiverInfo = input.caregiverParticipation || {};

    const sessionDates = input.sessions.map(s => s.session_date as string).sort();
    const periodStart = sessionDates[0] || new Date().toISOString().slice(0, 10);
    const periodEnd = sessionDates[sessionDates.length - 1] || new Date().toISOString().slice(0, 10);

    const goalProgress = input.goals.map((g: Record<string, unknown>) => {
      const goalOutcomes = input.outcomes.filter(o => o.goal_id === g.id);
      const goalInterventions = input.interventions.filter(i => i.goal_id === g.id);
      const goalSessions = new Set(goalInterventions.map(i => i.session_id as string));

      let currentLevel = 'No data recorded';
      let progressRating: PayerProgressReportOutput['goals_progress'][0]['progress_rating'] = 'minimal_progress';

      if (goalOutcomes.length >= 2) {
        const first = parseFloat(goalOutcomes[0].value as string);
        const last = parseFloat(goalOutcomes[goalOutcomes.length - 1].value as string);
        if (!isNaN(first) && !isNaN(last)) {
          const diff = last - first;
          if (diff > 20) progressRating = 'significant_progress';
          else if (diff > 5) progressRating = 'moderate_progress';
          else if (diff < -5) progressRating = 'regression';
          else if (Math.abs(diff) <= 5) progressRating = 'maintained';
        }
        currentLevel = `${goalOutcomes[goalOutcomes.length - 1].value} ${goalOutcomes[goalOutcomes.length - 1].unit || ''}`.trim();
      } else if (goalOutcomes.length === 1) {
        currentLevel = `${goalOutcomes[0].value} ${goalOutcomes[0].unit || ''}`.trim();
      }

      return {
        goal_description: g.description as string,
        domain: g.domain as string,
        baseline: g.baseline_value ? `${g.baseline_value} ${g.baseline_unit || ''}`.trim() : 'Not established',
        current_level: currentLevel,
        target: g.target_value ? `${g.target_value} ${g.target_unit || ''}`.trim() : 'Not specified',
        progress_rating: progressRating,
        sessions_addressed: goalSessions.size,
        interventions_used: goalInterventions.map(i => i.name as string),
        objective_data: goalOutcomes.length > 0
          ? `${goalOutcomes.length} measurement(s) recorded. Latest: ${currentLevel}.`
          : 'No objective data recorded for this reporting period.',
      };
    });

    const unresolvedBarriers = input.barriers.filter((b: Record<string, unknown>) => !b.resolution);

    return {
      report_type: 'medicaid_progress_report',
      patient_identifier: caseData.display_name || `Patient ${input.caseId.slice(0, 8)}`,
      reporting_period: { start: periodStart, end: periodEnd },
      diagnoses,
      authorization_info: `Authorized for ${caseData.session_length_minutes || 30}-minute sessions in ${(caseData.setting || '').replace(/_/g, ' ')} setting.`,
      goals_progress: goalProgress,
      session_summary: {
        total_sessions: input.sessions.length,
        attended: input.sessions.length,
        cancelled: 0,
        frequency: input.episodes.length > 0 ? (input.episodes[0].frequency as string || '2x/week') : '2x/week',
        duration_minutes: parseInt(caseData.session_length_minutes || '30'),
        setting: (caseData.setting || '').replace(/_/g, ' '),
      },
      barriers_to_progress: unresolvedBarriers.map((b: Record<string, unknown>) => `[${b.category}] ${b.description}`),
      caregiver_involvement: (caregiverInfo as Record<string, unknown>).present_mode
        ? `Caregiver participates ${(caregiverInfo as Record<string, unknown>).present_mode}. Session attendance rate: ${(caregiverInfo as Record<string, unknown>).session_attendance_rate || 'not tracked'}.`
        : 'Caregiver involvement not documented.',
      medical_necessity_justification: `Patient presents with ${diagnoses.join(', ')} requiring continued skilled speech-language pathology services. ${goalProgress.length} goal(s) documented, with progress being tracked. Documented progress indicates potential for continued functional improvement with ongoing treatment.`,
      continued_treatment_recommendation: `Continue ${(caseData.setting || '').replace(/_/g, ' ')} speech-language pathology services at current frequency and duration. ${unresolvedBarriers.length > 0 ? `${unresolvedBarriers.length} barrier(s) to progress have been identified and are being addressed.` : 'No significant barriers to continued progress.'}`,
      plan_modifications: goalProgress
        .filter(g => g.progress_rating === 'minimal_progress' || g.progress_rating === 'regression')
        .map(g => `Consider modifying approach for ${g.domain} domain goal: "${g.goal_description.slice(0, 50)}..." — ${g.progress_rating.replace(/_/g, ' ')} noted.`),
      clinician_signature_line: '________________________________\nLicensed Speech-Language Pathologist\nDate: _______________',
      knowledge_type: 'ai_generated',
      requires_clinician_review: true,
    };
  }

  async generatePatientSummary(input: PatientSummaryInput): Promise<PatientSummaryOutput> {
    const caseData = input.caseData as Record<string, string>;
    const diagnoses = JSON.parse(caseData.diagnoses || '[]') as string[];
    const precautions = JSON.parse(caseData.precautions || '[]') as string[];

    const activeGoals = input.goals.filter((g: Record<string, unknown>) => g.status === 'active');
    const recentSessions = input.sessions.slice(0, 5);

    const activeEpisodes = input.episodes.filter((ep: Record<string, unknown>) => ep.status === 'active');

    let patientSnapshot = `${caseData.age_band ? `Age band ${caseData.age_band}` : 'Patient'} in ${(caseData.setting || '').replace(/_/g, ' ')} setting.`;
    if (diagnoses.length > 0) {
      patientSnapshot += ` Diagnoses: ${diagnoses.join(', ')}.`;
    }
    if (activeEpisodes.length > 0) {
      const ep = activeEpisodes[0] as Record<string, string>;
      patientSnapshot += ` Currently in Episode ${ep.episode_number}${ep.frequency ? ` (${ep.frequency})` : ''}.`;
    }
    if (precautions.length > 0) {
      patientSnapshot += ` Active precautions: ${precautions.join('; ')}.`;
    }

    let treatmentSummary = '';
    if (activeGoals.length > 0) {
      treatmentSummary = `${activeGoals.length} active goal(s): ${activeGoals.map((g: Record<string, unknown>) => (g.description as string || '').slice(0, 60)).join('; ')}.`;
    } else {
      treatmentSummary = 'No active goals currently documented.';
    }
    treatmentSummary += ` ${input.sessions.length} visit(s) recorded to date.`;
    if (recentSessions.length > 0) {
      const latest = recentSessions[0] as Record<string, unknown>;
      treatmentSummary += ` Most recent visit: ${latest.session_date}, ${latest.duration_minutes} minutes.`;
    }

    let recentOutcomes = '';
    if (input.outcomes.length > 0) {
      const recent = input.outcomes.slice(0, 5);
      recentOutcomes = recent.map((o: Record<string, unknown>) =>
        `${o.metric}: ${o.value} ${o.unit}${o.assistance_level ? ` (${o.assistance_level})` : ''}`
      ).join('. ') + '.';
    } else {
      recentOutcomes = 'No outcome measurements recorded yet. Baseline data collection recommended.';
    }

    let activeBarriers = '';
    const unresolvedBarriers = input.barriers.filter((b: Record<string, unknown>) => !b.resolution);
    if (unresolvedBarriers.length > 0) {
      activeBarriers = unresolvedBarriers.map((b: Record<string, unknown>) =>
        `[${b.category}] ${b.description}`
      ).join('. ') + '.';
    } else {
      activeBarriers = 'No unresolved barriers documented.';
    }

    const nextSteps = recentSessions.length === 0
      ? 'Schedule initial visit and establish baseline measurements for active goals.'
      : `Continue current treatment approach. ${unresolvedBarriers.length > 0 ? 'Address documented barriers in upcoming sessions.' : ''} Monitor progress toward goal targets.`;

    return {
      patient_snapshot: patientSnapshot,
      treatment_summary: treatmentSummary,
      recent_outcomes: recentOutcomes,
      active_barriers: activeBarriers,
      next_steps: nextSteps,
      limitations: [
        'Generated by template-based mock provider — not a clinical assessment.',
        'All content requires clinician review before use in clinical decision-making.',
      ],
      knowledge_type: 'ai_generated',
      requires_clinician_review: true,
    };
  }
}
